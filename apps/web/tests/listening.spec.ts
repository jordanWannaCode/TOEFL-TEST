test('custom section controls and server progress survive a refresh', async ({ page }) => {
  const email = process.env['E2E_EMAIL'], password = process.env['E2E_PASSWORD'];
  if(!email || !password) throw new Error('Run scripts/e2e.sh.');
  await page.goto('/login'); await page.getByLabel('Email').fill(email); await page.getByLabel('Password').fill(password); await page.getByRole('button', { name:'Sign in', exact:true }).click();
  await page.getByRole('link', { name:'Open Listening practice' }).click();
  await page.getByRole('button', { name:'Start custom Listening section' }).click();
  await expect(page.getByRole('heading', { name:'Finding the lab' })).toBeVisible();
  await expect(page.getByLabel('Playback position')).toHaveCount(0);
  await page.getByRole('button', { name:'Play audio', exact:true }).click();
  await expect(page.getByTestId('audio-status')).toHaveText('Audio finished');
  await expect(page.getByRole('button', { name:'Replay audio', exact:true })).toBeDisabled();
  await page.getByRole('button', { name:'2. Conversation' }).click();
  await expect(page.getByRole('heading', { name:'A study room reservation' })).toBeVisible();
  const id = page.url().split('/').pop()!;
  const before = await (await page.request.get('/api/v1/sessions/' + id)).json();
  await page.getByRole('button', { name:'Play audio', exact:true }).click();
  await expect(page.getByTestId('audio-status')).toHaveText('Playing audio');
  await expect.poll(() => page.locator('audio').evaluate((audio: HTMLAudioElement) => audio.currentTime)).toBeGreaterThan(1);
  await page.reload();
  await expect(page.getByRole('heading', { name:'A study room reservation' })).toBeVisible();
  const after = await (await page.request.get('/api/v1/sessions/' + id)).json();
  expect(after.expiresAt).toBe(before.expiresAt); expect(after.currentPosition).toBe(1);
  await expect(page.getByRole('button', { name:'1. Choose a Response' })).toBeDisabled();
  await page.getByRole('button', { name:'Resume audio', exact:true }).click();
  await expect.poll(() => page.locator('audio').evaluate((audio: HTMLAudioElement) => audio.currentTime)).toBeGreaterThan(1);
  const state = await (await page.request.get(`/api/v1/sessions/${id}/items/${after.items[1].id}/playback`)).json();
  expect(state.plays).toBe(1);
});
test('strict playback does not restart an elapsed clip after refresh', async ({ page }) => {
  const email = process.env['E2E_EMAIL'], password = process.env['E2E_PASSWORD'];
  if(!email || !password) throw new Error('Run scripts/e2e.sh.');
  await page.goto('/login'); await page.getByLabel('Email').fill(email); await page.getByLabel('Password').fill(password); await page.getByRole('button', { name:'Sign in', exact:true }).click();
  await page.getByRole('link', { name:'Open Listening practice' }).click(); await page.getByRole('button', { name:'Start custom Listening section' }).click();
  await page.getByRole('button', { name:'Play audio', exact:true }).click(); await expect(page.getByTestId('audio-status')).toHaveText('Playing audio');
  const id = page.url().split('/').pop()!; await page.reload();
  const session = await (await page.request.get('/api/v1/sessions/' + id)).json(); const item = session.items[0];
  await expect.poll(async () => { const state = await (await page.request.get(`/api/v1/sessions/${id}/items/${item.id}/playback`)).json(); return state.positionMs; }).toBeGreaterThanOrEqual(item.content.stimulus.durationMs);
  await page.reload(); await page.getByRole('button', { name:'Resume audio', exact:true }).click();
  await expect(page.getByTestId('audio-status')).toHaveText('Audio finished');
  expect(await page.locator('audio').evaluate((audio: HTMLAudioElement) => audio.paused)).toBe(true);
  await expect(page.getByRole('button', { name:'Replay audio', exact:true })).toBeDisabled();
});
