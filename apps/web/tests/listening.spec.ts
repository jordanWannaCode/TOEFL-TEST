import { test, expect } from '@playwright/test';
test('Listening audio, answers, score, transcript and history form one real flow', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const email = process.env['E2E_EMAIL'], password = process.env['E2E_PASSWORD'];
  if(!email || !password) throw new Error('Run scripts/e2e.sh.');
  await page.goto('/login'); await page.getByLabel('Email').fill(email); await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name:'Sign in', exact:true }).click();
  await page.getByRole('link', { name:'Open Listening practice' }).click();
  await page.getByLabel('Task type', { exact:true }).selectOption('LISTEN_AND_CHOOSE_A_RESPONSE');
  await page.getByLabel('Difficulty', { exact:true }).selectOption('A2');
  await page.getByRole('button', { name:'Practice Finding the lab' }).click();
  await expect(page.getByRole('heading', { name:'Finding the lab' })).toBeVisible();
  await expect(page.getByRole('radio')).toHaveCount(0);
  await page.getByRole('button', { name:'Play audio', exact:true }).click();
  await expect(page.getByTestId('audio-status')).toHaveText('Audio finished', { timeout:15000 });
  await expect(page.getByRole('radio', { name:'On the second floor.' })).toBeVisible();
  await page.getByRole('radio', { name:'On the second floor.' }).check();
  await page.getByRole('button', { name:'Save answer', exact:true }).click();
  await expect(page.getByText('Saved on the server', { exact:true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('radio', { name:'On the second floor.' })).toBeChecked();
  page.once('dialog', dialog => dialog.accept()); await page.getByRole('button', { name:'Submit practice', exact:true }).click();
  await expect(page.getByTestId('objective-score')).toHaveText('1 / 1');
  await expect(page.getByText('The speaker asks for a location.', { exact:false })).toBeVisible();
  await page.getByRole('button', { name:'Review transcript' }).click();
  await expect(page.getByRole('region', { name:'Transcript' })).toContainText('Where is the lab?');
  await page.getByRole('link', { name:'Back to dashboard', exact:true }).click();
  await expect(page.getByText('Listening practice', { exact:true }).first()).toBeVisible();
  expect(errors).toEqual([]);
});
